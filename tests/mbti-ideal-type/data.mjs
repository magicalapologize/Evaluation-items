const OPTION_ORDERS = [
  [0, 1, 2, 3], [3, 2, 1, 0], [1, 3, 0, 2], [2, 0, 3, 1],
  [3, 0, 2, 1], [1, 2, 3, 0], [2, 3, 1, 0], [0, 2, 1, 3]
];

function makeQuestion(id, stage, axis, text, labels, orderIndex) {
  const scores = [-2, -1, 1, 2];
  const semanticOptions = labels.map((label, index) => ({ text: label, score: scores[index], intensity: Math.abs(scores[index]) }));
  const order = OPTION_ORDERS[orderIndex % OPTION_ORDERS.length];
  return { id, stage, axis, text, options: order.map((index) => semanticOptions[index]) };
}

