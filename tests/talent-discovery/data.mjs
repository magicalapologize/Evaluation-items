const KEYS = DIMENSIONS.map(({ key }) => key);
const ORDERS = [
  [0, 1, 2, 3], [1, 2, 3, 0], [2, 3, 0, 1], [3, 0, 1, 2],
  [0, 2, 3, 1], [1, 3, 0, 2], [2, 0, 1, 3], [3, 1, 2, 0]
];

function scoreVector(primary, secondary, level) {
  const scores = Object.fromEntries(KEYS.map((key) => [key, 0]));
  scores[primary] = level;
  if (secondary && level >= 2) scores[secondary] = 1;
  return scores;
}

function makeQuestion(id, scene, primary, secondary, text, options) {
  const order = ORDERS[(Number(id.replace(/\\D/g, "")) - 1) % ORDERS.length];
  return {
    id,
    scene: SCENES.find((item) => item.key === scene)?.name || scene,
    text,
    options: order.map((level, displayIndex) => ({
      text: options[level],
      scores: scoreVector(primary, secondary, level)
    }))
  };
}

