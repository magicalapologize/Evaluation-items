const DIMENSION_KEYS = DIMENSIONS.map(({ key }) => key);

const LEVELS = [
  { main: 0, support: 0 },
  { main: 1, support: 1 },
  { main: 2, support: 1 },
  { main: 3, support: 2 }
];

const ORDERS = [
  [0, 1, 2, 3], [1, 2, 3, 0], [2, 3, 0, 1], [3, 0, 1, 2],
  [0, 2, 3, 1], [1, 3, 0, 2], [2, 0, 1, 3], [3, 1, 2, 0]
];

function buildScores(primary, secondary, levelIndex) {
  const scores = Object.fromEntries(DIMENSION_KEYS.map((key) => [key, 0]));
  const level = LEVELS[levelIndex];
  scores[primary] = level.main;
  scores[secondary] = level.support;
  return scores;
}

function makeQuestion(id, scene, text, primary, secondary, optionTexts, order = Number(id) % ORDERS.length) {
  const permutation = ORDERS[order];
  return {
    id,
    scene,
    text,
    options: permutation.map((levelIndex) => ({
      text: optionTexts[levelIndex],
      scores: buildScores(primary, secondary, levelIndex)
    }))
  };
}

